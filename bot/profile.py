from __future__ import annotations

from aiogram import Bot

# Отображаемое имя бота (то, что видно в чатах, в поиске и в шапке
# профиля) — НЕ @username. Меняется либо отсюда (set_my_name ниже), либо
# вручную через /setname у @BotFather — это одно и то же поле Bot API,
# способы взаимозаменяемы. А вот сам @username (@tubedrop_bot) Bot API
# менять не умеет вообще — это делается только через /setusername у
# @BotFather, руками, один раз.
BOT_NAME = "TubeDrop"

# "О себе" — короткое описание на странице профиля бота и в превью, когда
# кто-то пересылает ссылку на бота другому человеку. Лимит Bot API — 120
# символов.
BOT_SHORT_DESCRIPTION = (
    "Простой способ сохранить видео или Shorts с YouTube в Telegram: "
    "ссылка → файл."
)

# Полное описание — то, что видно в пустом чате с ботом ДО нажатия
# "Старт". Лимит Bot API — 512 символов.
BOT_DESCRIPTION = (
    "👋 Я скачиваю видео и Shorts с YouTube и присылаю их прямо в этот чат.\n\n"
    "Пришли ссылку — покажу превью и доступные разрешения, ты выбираешь "
    "нужное, а дальше я сам скачаю файл. Во время скачивания показываю "
    "прогресс-бар, чтобы было видно, что всё идёт как надо, а не зависло.\n\n"
    "📜 Условия использования — /terms"
)


async def set_bot_profile(bot: Bot) -> None:
    """Устанавливает имя, "о себе" и описание бота — РАЗОВОЕ действие,
    вызывать вручную (например, из интерактивного python -m asyncio или
    небольшого одноразового скрипта), а НЕ из bot/main.py при каждом
    старте.

    Раньше вызывалась автоматически на каждом запуске бота (тем же
    способом, каким set_bot_commands устанавливает командное меню) —
    "идемпотентно, лишний вызов ничего не ломает" звучало разумно для
    setMyCommands, но не подтвердилось для setMyName: у него отдельный,
    гораздо более жёсткий флуд-контроль на стороне Telegram, и частые
    перезапуски бота (обычное дело при итеративном деплое) упёрлись в
    TelegramRetryAfter на несколько часов (14667 секунд в реальном
    случае — это ~4 часа). set_my_short_description/set_my_description
    таким лимитам, судя по всему, не подвержены, но раз одного вызова
    из трёх достаточно, чтобы уронить весь набор при рестарте, безопаснее
    убрать все три из автозапуска, а не только виновника.
    """
    await bot.set_my_name(BOT_NAME)
    await bot.set_my_short_description(BOT_SHORT_DESCRIPTION)
    await bot.set_my_description(BOT_DESCRIPTION)
